// ---------------------------------------------------------------- CSV

/** Neutralise spreadsheet formula injection (CWE-1236) and quote per RFC 4180. */
export function csvCell(v: unknown): string {
  let s = v === null || v === undefined ? '' : String(v);
  if (/^[=+\-@\t\r]/.test(s)) s = `'${s}`;
  return /[",\r\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
}

export function toCsv(r: Report): string {
  const lines = [r.columns.map((c) => csvCell(c.label)).join(',')];
  for (const row of r.rows) lines.push(r.columns.map((c) => csvCell(row[c.key])).join(','));
  return '﻿' + lines.join('\r\n') + '\r\n';
}

// ---------------------------------------------------------------- XLSX

export async function toXlsx(r: Report): Promise<Buffer> {
  const wb = new ExcelJS.Workbook();
  wb.creator = APP_NAME;
  wb.created = new Date();
  const ws = wb.addWorksheet(r.type.charAt(0).toUpperCase() + r.type.slice(1), {
    pageSetup: { orientation: 'landscape', fitToPage: true, fitToWidth: 1, fitToHeight: 0, paperSize: 9 },
    headerFooter: { oddFooter: `&L${r.meta.university}&RPage &P of &N` },
  });
  const ncol = r.columns.length;
  const title = (text: string, size: number, bold = true) => {
    const row = ws.addRow([text]);
    ws.mergeCells(row.number, 1, row.number, ncol);
    row.getCell(1).font = { size, bold, color: { argb: 'FF1B2A41' } };
    return row;
  };
  title(r.meta.university, 14);
  if (r.meta.unit) title(r.meta.unit, 10, false);
  title('Guest Faculty & Sports Coach Attendance Report', 12);
  title(`${r.title} — ${r.period}`, 11);
  ws.addRow([]);
  for (const f of r.filters) ws.addRow([f.label, f.value]).getCell(1).font = { bold: true };
  ws.addRow(['Generated', r.meta.generatedAt]).getCell(1).font = { bold: true };
  ws.addRow(['Generated by', r.meta.generatedBy]).getCell(1).font = { bold: true };
  ws.addRow([]);

  const header = ws.addRow(r.columns.map((c) => c.label));
  header.eachCell((cell) => {
    cell.font = { bold: true, color: { argb: 'FFFFFFFF' } };
    cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FF1B2A41' } };
    cell.alignment = { vertical: 'middle', wrapText: true };
    cell.border = { bottom: { style: 'thin' } };
  });
  const headerRow = header.number;
  for (const row of r.rows) {
    const added = ws.addRow(r.columns.map((c) => row[c.key] ?? ''));
    r.columns.forEach((c, i) => {
      if (c.align === 'right') added.getCell(i + 1).alignment = { horizontal: 'right' };
    });
  }
  ws.autoFilter = { from: { row: headerRow, column: 1 }, to: { row: headerRow, column: ncol } };
  ws.views = [{ state: 'frozen', ySplit: headerRow }];
  r.columns.forEach((c, i) => {
    const maxLen = Math.max(c.label.length, ...r.rows.map((row) => String(row[c.key] ?? '').length));
    ws.getColumn(i + 1).width = Math.min(45, Math.max(10, maxLen + 2));
  });
  ws.getColumn(1).width = Math.max(ws.getColumn(1).width ?? 10, 18);

  ws.addRow([]);
  ws.addRow(['Summary']).getCell(1).font = { bold: true, size: 11 };
  for (const s of r.summary) ws.addRow([s.label, s.value]);
  if (r.notes.length) {
    ws.addRow([]);
    ws.addRow(['Calculation notes']).getCell(1).font = { bold: true };
    for (const n of r.notes) ws.addRow([n]);
  }
  ws.addRow([]);
  ws.addRow([r.meta.footer]).getCell(1).font = { italic: true, size: 9, color: { argb: 'FF555555' } };
  return Buffer.from(await wb.xlsx.writeBuffer());
}

// ---------------------------------------------------------------- PDF

/** Built-in PDF fonts are WinAnsi; map a few typographic characters and drop the rest. */
function pdfText(v: unknown): string {
  return String(v ?? '')
    .replace(/→/g, 'to')
    .replace(/[–−]/g, '-')
    .replace(/[“”]/g, '"')
    .replace(/[‘’]/g, "'")
    .replace(/[\t\r\n]+/g, ' ')
    .replace(/[^ -~\u00A1-\u00FF\u2014\u2022]/g, (c) => (c === '\u00A0' ? ' ' : '?'));
}

export function toPdf(r: Report): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ size: 'A4', layout: 'landscape', margins: { top: 40, bottom: 50, left: 36, right: 36 }, bufferPages: true, info: { Title: pdfText(`${r.title} - ${r.period}`), Author: APP_NAME, Creator: APP_NAME } });
    const chunks: Buffer[] = [];
    doc.on('data', (c) => chunks.push(c));
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);

    const INK = '#1B2A41';
    const MUTED = '#5B6472';
    const RULE = '#C9CED6';
    const left = doc.page.margins.left;
    const usable = doc.page.width - doc.page.margins.left - doc.page.margins.right;

    // --- Letterhead
    const logoSize = 46;
    const logoFile = r.meta.logoPath ? path.join(config.uploadDir, r.meta.logoPath) : null;
    if (logoFile && fs.existsSync(logoFile)) {
      try {
        doc.image(logoFile, left, 36, { fit: [logoSize, logoSize] });
      } catch {
        /* unreadable logo: fall back to placeholder */
      }
    } else {
      doc.save().rect(left, 36, logoSize, logoSize).lineWidth(0.8).dash(2, { space: 2 }).strokeColor(RULE).stroke().undash().restore();
      doc.fontSize(6).fillColor(MUTED).text('LOGO', left, 36 + logoSize / 2 - 3, { width: logoSize, align: 'center' });
    }
    const tx = left + logoSize + 12;
    doc.fillColor(INK).font('Helvetica-Bold').fontSize(14).text(pdfText(r.meta.university), tx, 38, { width: usable - logoSize - 12 });
    if (r.meta.unit) doc.font('Helvetica').fontSize(9).fillColor(MUTED).text(pdfText(r.meta.unit), tx, doc.y + 1);
    doc.font('Helvetica-Bold').fontSize(10).fillColor(INK).text('Guest Faculty & Sports Coach Attendance Report', tx, doc.y + 2);
    const afterHead = Math.max(doc.y, 36 + logoSize) + 8;
    doc.moveTo(left, afterHead).lineTo(left + usable, afterHead).lineWidth(1.2).strokeColor(INK).stroke();

    // --- Title block
    doc.font('Helvetica-Bold').fontSize(13).fillColor(INK).text(pdfText(r.title), left, afterHead + 10);
    doc.font('Helvetica').fontSize(10).fillColor(INK).text(pdfText(r.period));
    doc.moveDown(0.4);
    const metaY = doc.y;
    const colW = usable / 2;
    doc.fontSize(8.5).fillColor(MUTED);
    let y1 = metaY;
    for (const f of r.filters) {
      doc.font('Helvetica-Bold').fillColor(INK).text(pdfText(`${f.label}: `), left, y1, { continued: true }).font('Helvetica').fillColor(MUTED).text(pdfText(f.value), { width: colW - 10 });
      y1 = doc.y;
    }
    let y2 = metaY;
    for (const [k, v] of [
      ['Generated', r.meta.generatedAt],
      ['Generated by', r.meta.generatedBy],
    ]) {
      doc.font('Helvetica-Bold').fillColor(INK).text(`${k}: `, left + colW, y2, { continued: true }).font('Helvetica').fillColor(MUTED).text(pdfText(v), { width: colW });
      y2 = doc.y;
    }
    doc.y = Math.max(y1, y2) + 8;

    // --- Table
    const totalW = r.columns.reduce((s, c) => s + (c.width ?? 70), 0);
    const scale = usable / totalW;
    const widths = r.columns.map((c) => (c.width ?? 70) * scale);
    const pad = 3;
    const fontSize = 7.5;
    const bottomLimit = () => doc.page.height - doc.page.margins.bottom - 10;

    const drawHeader = () => {
      doc.font('Helvetica-Bold').fontSize(fontSize);
      const h = Math.max(...r.columns.map((c, i) => doc.heightOfString(pdfText(c.label), { width: widths[i] - pad * 2 }))) + pad * 2;
      const y = doc.y;
      doc.rect(left, y, usable, h).fill(INK);
      let x = left;
      r.columns.forEach((c, i) => {
        doc.fillColor('#FFFFFF').text(pdfText(c.label), x + pad, y + pad, { width: widths[i] - pad * 2, align: c.align ?? 'left' });
        x += widths[i];
      });
      doc.y = y + h;
    };

    if (r.rows.length === 0) {
      doc.font('Helvetica-Oblique').fontSize(10).fillColor(MUTED).text('No records found for the selected filters.', left, doc.y + 6);
    } else {
      drawHeader();
      r.rows.forEach((row, idx) => {
        doc.font('Helvetica').fontSize(fontSize);
        const cells = r.columns.map((c) => pdfText(row[c.key] ?? ''));
        const h = Math.max(...cells.map((t, i) => doc.heightOfString(t || ' ', { width: widths[i] - pad * 2 }))) + pad * 2;
        if (doc.y + h > bottomLimit()) {
          doc.addPage();
          doc.y = doc.page.margins.top;
          drawHeader();
          doc.font('Helvetica').fontSize(fontSize);
        }
        const y = doc.y;
        if (idx % 2 === 1) doc.rect(left, y, usable, h).fill('#F3F5F8');
        let x = left;
        cells.forEach((t, i) => {
          doc.fillColor('#111111').text(t, x + pad, y + pad, { width: widths[i] - pad * 2, align: r.columns[i].align ?? 'left' });
          x += widths[i];
        });
        doc.moveTo(left, y + h).lineTo(left + usable, y + h).lineWidth(0.3).strokeColor(RULE).stroke();
        doc.y = y + h;
      });
    }

    // --- Summary
    const need = 30 + r.summary.length * 12 + r.notes.length * 11;
    if (doc.y + Math.min(need, 200) > bottomLimit()) {
      doc.addPage();
      doc.y = doc.page.margins.top;
    }
    doc.moveDown(1);
    doc.font('Helvetica-Bold').fontSize(10).fillColor(INK).text('Summary', left);
    doc.moveDown(0.2);
    doc.fontSize(8.5);
    for (const s of r.summary) {
      doc.font('Helvetica-Bold').fillColor(INK).text(pdfText(`${s.label}: `), left, doc.y, { continued: true }).font('Helvetica').fillColor('#111111').text(pdfText(s.value));
    }
    if (r.notes.length) {
      doc.moveDown(0.5);
      doc.font('Helvetica-Bold').fontSize(8.5).fillColor(INK).text('Calculation notes', left);
      doc.font('Helvetica').fontSize(8).fillColor(MUTED);
      for (const n of r.notes) doc.text(pdfText(`• ${n}`), left, doc.y, { width: usable });
    }
    doc.moveDown(2);
    if (doc.y + 30 > bottomLimit()) {
      doc.addPage();
      doc.y = doc.page.margins.top + 20;
    }
    const sigY = doc.y + 18;
    doc.moveTo(left + usable - 180, sigY).lineTo(left + usable, sigY).lineWidth(0.5).strokeColor(MUTED).stroke();
    doc.font('Helvetica').fontSize(8).fillColor(MUTED).text('Signature of Authorized Officer', left + usable - 180, sigY + 3, { width: 180, align: 'center' });

    // --- Footer with page numbers on every page
    const range = doc.bufferedPageRange();
    for (let i = range.start; i < range.start + range.count; i++) {
      doc.switchToPage(i);
      const fy = doc.page.height - doc.page.margins.bottom + 14;
      const saveBottom = doc.page.margins.bottom;
      doc.page.margins.bottom = 0;
      doc.moveTo(left, fy - 4).lineTo(left + usable, fy - 4).lineWidth(0.5).strokeColor(RULE).stroke();
      doc.font('Helvetica').fontSize(7).fillColor(MUTED);
      doc.text(pdfText(`${APP_NAME} — ${APP_SUBTITLE}. ${r.meta.footer}`), left, fy, { width: usable - 90, lineBreak: true, height: 20 });
      doc.text(`Page ${i - range.start + 1} of ${range.count}`, left + usable - 90, fy, { width: 90, align: 'right' });
      doc.page.margins.bottom = saveBottom;
    }
    doc.end();
  });
}
